// Checks actual personal templates, sharing and the clock-driven scheduler on the isolated stack.
import { createRequire } from "node:module";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { setTimeout as delay } from "node:timers/promises";
const {chromium} = createRequire(import.meta.url)(process.env.PLAYWRIGHT_PACKAGE || "@playwright/test");
const origin="http://127.0.0.1:18831", peerOrigin="http://127.0.0.1:18832", tag=randomUUID().slice(0,8);
const browser=await chromium.launch({channel:"chrome"});
const name="個人週報 "+tag, scheduleName="時刻動作確認 "+tag;
let scheduleId;
try {
  const page=await browser.newPage(), peer=await browser.newPage({viewport:{width:390,height:844}});
  page.setDefaultTimeout(20000); peer.setDefaultTimeout(20000);
  await page.goto(origin+"/#skills");
  await page.getByRole("button",{name:"手順を作成",exact:true}).click();
  await page.getByLabel("手順名").fill(name);
  await page.getByLabel("依頼の種類").selectOption("weekly");
  await page.getByLabel("毎回の依頼内容").fill("仕事の記録から今週の週報をまとめて");
  await page.getByLabel("出力形式").fill("「完了」「課題」「来週の予定」の見出しに分ける");
  await page.getByRole("button",{name:"自分用に保存"}).click();
  await page.locator("#catalogResults button").filter({hasText:name}).click();
  await page.getByRole("button",{name:"依頼内容と出力形式を設定"}).click();
  assert.match(await page.getByLabel("引き継ぐ出力形式").inputValue(),/来週の予定/);
  await page.getByText("自分の資料を使う",{exact:true}).click();
  await page.getByLabel("週の進捗記録").fill("東支店で青葉研修を完了。課題は参加枠の不足。来週は第二回を予定。");
  await page.getByRole("button",{name:"新しい仕事として依頼"}).click();
  await page.locator("#memoText").waitFor({timeout:180000});
  const memo=await page.locator("#memoText").innerText(), id=page.url().split("#job/")[1];
  assert.match(memo,/青葉/);
  await peer.goto(peerOrigin+"/#skills");
  await peer.getByRole("button",{name:"自分が作成"}).click();
  assert.equal(await peer.locator("#catalogResults button").filter({hasText:name}).count(),0);
  await page.getByRole("button",{name:"同僚に共有"}).click();
  assert.equal(await page.locator("#dialog .doc-body").innerText(),memo);
  await page.getByLabel("共有する相手").selectOption("tanaka");
  await page.getByRole("button",{name:"この内容を共有する"}).click();
  await page.getByText("指定した相手に共有しました。").waitFor();
  await peer.goto(peerOrigin+"/#work/projects");
  const share=peer.locator('[data-op^="shared/"]').first();
  await share.click();
  assert.equal(await peer.locator("#main .doc-body").innerText(),memo);
  assert.equal(await peer.getByRole("button",{name:/出典.*を開く/}).count(),0);
  assert.equal((await peer.request.get(peerOrigin+"/api/jobs/"+id)).status(),404);
  console.log("recipient snapshot verified");
  await page.goto(origin+"/#jobs/reservations");
  await page.getByRole("button",{name:"週報を設定"}).click();
  await page.getByLabel("名前",{exact:true}).fill(scheduleName);
  const due=new Date(Date.now()+75000+9*3600000);
  const time=due.toISOString().slice(11,16);
  await page.getByLabel("曜日",{exact:true}).selectOption(String(due.getUTCDay()));
  await page.getByLabel("実行時刻（日本時間）").fill(time);
  await page.getByRole("button",{name:"定期実行を登録"}).click();
  const row=page.locator(".planning-schedule-row").filter({hasText:scheduleName});
  await row.waitFor();
  const schedule=async()=>(await (await page.request.get(origin+"/api/workspace")).json()).schedules.find(s=>s.name===scheduleName);
  scheduleId=(await schedule()).id; console.log("waiting for weekly schedule",scheduleId,time);
  const deadline=Date.now()+160000;
  let scheduledJob;
  do {
    scheduledJob=(await schedule()).last_job;
    if(scheduledJob) break;
    await delay(2000);
  } while(Date.now()<deadline);
  assert.ok(scheduledJob,"clock did not dispatch weekly work");
  await page.reload();
  await row.getByRole("button",{name:"一時停止"}).click();
  await row.getByRole("button",{name:"再開"}).waitFor();
  await row.getByRole("link",{name:"前回の仕事を開く"}).click();
  await page.locator("#memoText").waitFor({timeout:180000});
  assert.ok(page.url().endsWith(scheduledJob));
  assert.match(await page.locator("#memoText").innerText(),/青葉/);
  console.log(JSON.stringify({template:name, sharedJob:id, scheduledJob, jstTime:time, paused:true}));
} catch (e) { console.error(e); throw e; } finally {
  if(scheduleId) await fetch(origin+"/api/schedules/"+scheduleId,{method:"POST",headers:{Origin:origin,"Content-Type":"application/json"},body:'{"enabled":false}'}).catch(()=>{});
  await browser.close();
}
